import os, shutil, subprocess, sys
sys.path.insert(0, "tools")
import build_demo as bd
rt = open("src/realtime_3d.i").read()
old_pal = """    move.w  #$0001,2(a1)
    move.w  #$0112,6(a1)
    move.w  #$0234,10(a1)
    move.w  #$0356,14(a1)
    move.w  #$0146,18(a1)
    move.w  #$04bc,22(a1)
    move.w  #$0e93,26(a1)
    move.w  #$0ffd,30(a1)"""
new_pal = """    move.w  #$0002,2(a1)
    move.w  #$0247,6(a1)
    move.w  #$0369,10(a1)
    move.w  #$059c,14(a1)
    move.w  #$0258,18(a1)
    move.w  #$04de,22(a1)
    move.w  #$0fb3,26(a1)
    move.w  #$0fff,30(a1)"""
rt = rt.replace(old_pal, new_pal).replace("add.w   #56,d0", "add.w   #34,d0")
open("src/realtime_3d.i", "w").write(rt)
sd, od = "src", "releases"
exe = os.path.abspath(f"{od}/GROTTO3D")
subprocess.run(["vasmm68k_mot", "-m68020", "-Fhunkexe", "-kick1hunks", "-nosym", "-I.", "main.s", "-o", exe], cwd=sd, check=True)
os.chmod(exe, 0o755)
sz = os.path.getsize(exe)
em = ((sz + 0x120000 + 0xFFFF) & ~0xFFFF)
lo = em - sz - 256
pr = f"{od}/_tmp_grotto3d"
shutil.rmtree(pr, ignore_errors=True); os.makedirs(f"{pr}/Grotto3D", exist_ok=True)
shutil.copy2(exe, f"{pr}/Grotto3D/GROTTO3D")
open(f"{pr}/Grotto3D/README.txt", "w").write("Grotto 3D (Amiga 1200 AGA / 68020)\nCode: malek69 & Gemini AI\nMusic: 1991-Not A Number (Aminet)\n")
sl = open(f"{sd}/whdload_slave.s").read().replace("{EXP_MEM}", f"{em:08x}").replace("{LOAD_OFF}", f"{lo:08x}").replace("{DEMO_TITLE}", "Grotto 3D").replace("{DEMO_CREDITS}", "Code: malek69 & Gemini AI | Music: 1991-Not A Number").replace("{EXE_NAME}", "GROTTO3D")
open(f"{pr}/slave.s", "w").write(sl)
subprocess.run(["vasmm68k_mot", "-m68020", "-Fhunkexe", "-nosym", f"{pr}/slave.s", "-o", f"{pr}/Grotto3D/Grotto3D.slave"], check=True)
os.remove(f"{pr}/slave.s")
open(f"{pr}/Grotto3D.info", "wb").write(bd.mk_ico(2))
open(f"{pr}/Grotto3D/Grotto3D.info", "wb").write(bd.mk_ico(4, "WHDLoad", ["SLAVE=Grotto3D.slave", "NoMMU"]))
if os.path.exists(f"{od}/grotto3d.lha"): os.remove(f"{od}/grotto3d.lha")
bd.mk_lha(f"{od}/grotto3d.lha", pr)
shutil.rmtree(pr)
print(f"SUKCES: {exe} ({sz/1024:.1f} KB) | Gotowe: releases/grotto3d.lha + README.txt!", flush=True)
